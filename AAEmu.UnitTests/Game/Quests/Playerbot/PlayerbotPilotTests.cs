    #region Seeded-regression proof (required work item 5)

    /// <summary>
    /// Seeded defect: quest 251's report target is wrong (NpcId swapped to a
    /// non-existent NPC). The bot must FAIL the turn-in with a repro trace;
    /// reverting the defect must restore green (fail-before / pass-after at
    /// bot level — the regression-harness contract in action).
    /// </summary>
    [Test]
    public async Task SeededDefect_WrongReportNpc_FailBefore_PassAfter()
    {
        PlayerbotPilotRig.SeedPilotSingletons();
        var manifest = LoadManifest("t1", 251);

        // ---- FAIL-BEFORE: inject the defect into the loaded template ----
        var template = AAEmu.Game.Core.Managers.QuestManager.Instance.GetTemplate(251);
        var reportAct = template.Components.Values
            .SelectMany(c => c.ActTemplates)
            .OfType<AAEmu.Game.Models.Game.Quests.Acts.QuestActConReportNpc>()
            .First();
        var originalNpcId = reportAct.NpcId;
        reportAct.NpcId = 999999; // wrong report target (data-defect class)

        var (bot, session) = NewBot("seeded-fail");
        var failResult = PlayerbotQuestDriver.DriveQuest(bot, session, manifest, 1);
        await Assert.That(failResult.Passed, "seeded defect must FAIL the bot run").IsFalse();
        await Assert.That(failResult.FailStage is "READY" or "REWARD" or "VERIFY",
            "failure must surface at turn-in/completion, got " + failResult.FailStage).IsTrue();
        Console.WriteLine("FAIL-BEFORE repro trace:\n" + failResult.ReproTrace());

        // ---- PASS-AFTER: revert the defect ----
        reportAct.NpcId = originalNpcId;

        var (bot2, session2) = NewBot("seeded-pass");
        var passResult = PlayerbotQuestDriver.DriveQuest(bot2, session2, manifest, 1);
        await Assert.That(passResult.Passed,
            "reverted defect must PASS the bot run: " + passResult.ReproTrace()).IsTrue();
    }

