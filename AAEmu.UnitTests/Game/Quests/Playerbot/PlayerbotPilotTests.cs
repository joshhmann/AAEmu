    #region Restart persistence + cross-cycle isolation (required work item 4)

    /// <summary>
    /// Restart persistence: mid-quest disconnect -> reconnect (fresh session,
    /// quest state restored via the engine's ReadData path) must resume
    /// without duplication or loss. Full-state match on 2 checkpoints.
    ///
    /// Checkpoint design: each checkpoint quest (254, 266) is prepared
    /// mid-flight — accepted + progressed to Ready but NOT turned in — because
    /// that is the state a disconnect must survive. Completed route quests
    /// drop out of ActiveQuests (engine terminal state), so checkpointing
    /// between quests would snapshot nothing.
    /// </summary>
    [Test]
    public async Task RestartPersistence_TwoCheckpoints_FullStateMatch()
    {
        PlayerbotPilotRig.SeedPilotSingletons();
        var manifests = GoldenRoute.ToDictionary(q => q, q => LoadManifest("t1", q));

        var checkpoints = new uint[] { 254, 266 }; // mid-chain, both have a real Progress step
        foreach (var checkpointQuest in checkpoints)
        {
            // Drive everything BEFORE the checkpoint to completion on the live bot.
            var (bot, session) = NewBot($"restart-{checkpointQuest}");
            foreach (var questId in GoldenRoute)
            {
                if (questId == checkpointQuest)
                    break;
                var manifest = manifests[questId];
                var level = (byte)Math.Max(bot.Character.Level, manifest.Template.Level);
                var result = PlayerbotQuestDriver.DriveQuest(bot, session, manifest, level);
                await Assert.That(result.Passed, "pre-checkpoint drive failed: " + result.ReproTrace()).IsTrue();
            }

            // Prepare the checkpoint quest mid-flight (accepted + progressed,
            // not turned in) — the state a disconnect must survive. The exact
            // step differs per quest shape (254 has no Progress component and
            // rests at Ready; 266's objective-satisfied Progress rests at
            // Progress/Ready) — what matters is it is ACTIVE and not complete,
            // so there is real state to snapshot.
            var cpManifest = manifests[checkpointQuest];
            var cpLevel = (byte)Math.Max(bot.Character.Level, cpManifest.Template.Level);
            var prepared = PlayerbotQuestDriver.PrepareQuest(bot, session, cpManifest, cpLevel);
            await Assert.That(prepared, $"checkpoint {checkpointQuest}: quest must be active after prepare").IsNotNull();
            await Assert.That(bot.HasCompleted(checkpointQuest),
                $"checkpoint {checkpointQuest}: prepared quest must NOT be completed").IsFalse();

            // Snapshot all active quest state (the "save").
            var snapshot = bot.Character.Quests.ActiveQuests.Values
                .Select(q => new { q.TemplateId, Data = q.WriteData(), Step = q.Step, Status = q.Status })
                .ToList();
            await Assert.That(snapshot.Count,
                $"checkpoint {checkpointQuest}: expected active quests to snapshot").IsGreaterThan(0);

            // "Restart": fresh session, restore via the engine's load path
            // (same as CharacterQuests.Load: new Quest(template, owner) + ReadData).
            var (restartBot, restartSession) = NewBot($"restarted-{checkpointQuest}");
            foreach (var entry in snapshot)
            {
                var template = AAEmu.Game.Core.Managers.QuestManager.Instance.GetTemplate(entry.TemplateId);
                var restored = new Quest(template, restartBot.Character);
                restored.Id = entry.TemplateId;
                restored.TemplateId = entry.TemplateId;
                restored.Status = entry.Status;
                restored.ReadData(entry.Data);
                restartBot.Character.Quests.ActiveQuests.Add(entry.TemplateId, restored);
                restored.QuestInitialized();
                restored.RequestEvaluation();
            }

            // Full-state match: byte-identical re-serialization + step/status equality.
            var restartState = restartBot.Character.Quests.ActiveQuests.Values
                .Select(q => new { q.TemplateId, Data = q.WriteData(), Step = q.Step, Status = q.Status })
                .ToList();

            await Assert.That(restartState.Count,
                $"checkpoint {checkpointQuest}: active quest count changed after restart").IsEqualTo(snapshot.Count);
            foreach (var entry in snapshot)
            {
                var restored = restartState.FirstOrDefault(r => r.TemplateId == entry.TemplateId);
                await Assert.That(restored, $"checkpoint {checkpointQuest}: quest {entry.TemplateId} lost on restart").IsNotNull();
                await Assert.That(restored!.Data.SequenceEqual(entry.Data),
                    $"checkpoint {checkpointQuest}: quest {entry.TemplateId} WriteData round-trip byte mismatch (duplication/loss)").IsTrue();
                await Assert.That(restored.Step,
                    $"checkpoint {checkpointQuest}: step drift on quest {entry.TemplateId}").IsEqualTo(entry.Step);
                await Assert.That(restored.Status,
                    $"checkpoint {checkpointQuest}: status drift on quest {entry.TemplateId}").IsEqualTo(entry.Status);
            }

            // No duplication: restarting twice must not duplicate quest rows.
            await Assert.That(restartBot.Character.Quests.ActiveQuests.Count,
                $"checkpoint {checkpointQuest}: restart duplicated active quests").IsEqualTo(snapshot.Count);

            // Resume the prepared quest through the REAL turn-in path on the
            // restarted bot — the reconnect must finish what the disconnect
            // interrupted, with the same reward outcome.
            var resumed = PlayerbotQuestDriver.ResumePreparedQuest(restartBot, restartSession, cpManifest);
            await Assert.That(resumed.Passed,
                $"checkpoint {checkpointQuest}: resume after restart failed: " + resumed.ReproTrace()).IsTrue();
            await Assert.That(restartBot.HasCompleted(checkpointQuest),
                $"checkpoint {checkpointQuest}: completed flag must be set after resume").IsTrue();
            await Assert.That(restartBot.IsActive(checkpointQuest),
                $"checkpoint {checkpointQuest}: quest must drop from ActiveQuests after resume").IsFalse();
        }
    }

    /// <summary>
    /// Cross-cycle isolation: cycle N+1 starts from the same baseline as
    /// cycle 1 — byte-identical start state (no cumulative drift).
    /// </summary>
    [Test]
    public async Task CrossCycleIsolation_BaselineByteIdentical()
    {
        PlayerbotPilotRig.SeedPilotSingletons();

        var baseline = CaptureBaseline(NewBot("baseline").Bot);
        for (var cycle = 2; cycle <= 5; cycle++)
        {
            var (bot, _) = NewBot($"iso-c{cycle}");
            var state = CaptureBaseline(bot);
            await Assert.That(state,
                $"cycle {cycle}: baseline drifted (cross-cycle isolation violated)").IsEqualTo(baseline);
        }
    }

    private static string CaptureBaseline(PlayerBotController bot)
    {
        // Byte-identical start state: no active quests, no completed flags,
        // empty inventory, starting level.
        var sb = new StringBuilder();
        sb.Append("active=").Append(bot.Character.Quests.ActiveQuests.Count).Append(';');
        sb.Append("level=").Append(bot.Character.Level).Append(';');
        sb.Append("inv=").Append(bot.InventoryCount(0)).Append(';');
        var anyCompleted = false;
        for (var i = 0; i < 5000; i += 64)
            anyCompleted |= bot.HasCompleted((uint)i);
        sb.Append("completed=").Append(anyCompleted);
        return sb.ToString();
    }

