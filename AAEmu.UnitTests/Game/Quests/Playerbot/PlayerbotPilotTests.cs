    #region Helpers

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir != null && !Directory.Exists(Path.Combine(dir.FullName, ".git")))
            dir = dir.Parent;
        return dir?.FullName
               ?? throw new InvalidOperationException("Cannot locate repo root from " + AppContext.BaseDirectory);
    }

    private static QuestScenarioManifest LoadManifest(string tier, uint questId)
    {
        var path = Path.Combine(RepoRoot(), "AAEmu.UnitTests", "Game", "Quests", "Scenario", "Manifests", tier,
            $"{questId}.json");
        if (!File.Exists(path))
            throw new InvalidOperationException($"No manifest for quest {questId} at {path}");
        return QuestScenarioManifest.LoadFromFile(path);
    }

    private static (PlayerBotController Bot, HeadlessSession Session) NewBot(string name, byte level = 1)
    {
        var session = HeadlessSession.Create((uint)(name.GetHashCode() & 0xFFFF), name, level, Race.Nuian);
        return (new PlayerBotController(session.Character), session);
    }

    /// <summary>Emits the M2b metrics table to scorecard-explorations/m2b-pilot-metrics.md
    /// (deterministic header — no wall-clock churn, same discipline as the census).</summary>
    private static void EmitMetricsTable(PilotRun run, string curriculumLabel)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# M2b playerbot pilot metrics — " + curriculumLabel);
        sb.AppendLine();
        sb.AppendLine("> Generated by PlayerbotPilotTests (deterministic — no wall-clock).");
        sb.AppendLine("> Engine: real QuestManager.Load + real unit_reqs from canonical compact.sqlite3;");
        sb.AppendLine("> bots = ordinary Character records (no Connection); accept/turn-in via real engine paths.");
        sb.AppendLine();
        sb.AppendLine("| Metric | Definition | Green bar | Observed |");
        sb.AppendLine("|---|---|---|---|");
        sb.AppendLine();

        var grouped = run.Cycles.GroupBy(c => c.Bot).OrderBy(g => g.Key).ToList();
        foreach (var botGroup in grouped)
        {
            var attempts = botGroup.Count();
            var passed = botGroup.Count(c => c.Passed);
            sb.AppendLine($"| Bot {botGroup.Key} | cycles {passed}/{attempts} | 100% | {passed * 100.0 / attempts:0.0}% |");
        }

        // Mean cycles-to-complete over the last 5 cycles (deterministic drive -> 1.0).
        var last5 = run.Cycles.OrderByDescending(c => (c.Bot, c.Cycle)).Take(Math.Min(5 * grouped.Count, run.Cycles.Count));
        var meanCtc = last5.Any() ? last5.Average(c => c.Passed ? 1 : 0) : double.NaN;
        sb.AppendLine();
        sb.AppendLine($"| Mean cycles-to-complete | avg cycles to first full pass (last 5 cycles) | stable ±1 | {meanCtc:0.00} |");
        sb.AppendLine();

        var leakCount = run.Cycles.Sum(c => c.CleanupLeaks.Count);
        sb.AppendLine($"| State-cleanup | leaks over the run (ActiveQuests, completed-flag dupes, orphaned component state, reward totals) | 0 leaks | {leakCount} |");
        sb.AppendLine();
        sb.AppendLine("## Per-cycle detail");
        sb.AppendLine();
        sb.AppendLine("| Bot | Cycle | Quests | Passed | Cleanup leaks |");
        sb.AppendLine("|---|---|---|---|---|");
        foreach (var c in run.Cycles.OrderBy(c => c.Bot).ThenBy(c => c.Cycle))
        {
            var leaks = c.CleanupLeaks.Count == 0 ? "none" : string.Join("; ", c.CleanupLeaks);
            sb.AppendLine($"| {c.Bot} | {c.Cycle} | {c.TotalQuests} | {c.PassedQuests} | {leaks} |");
        }

        if (run.Failures.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("## Failures (drift — every entry is a regression card)");
            sb.AppendLine();
            foreach (var f in run.Failures)
                sb.AppendLine("- " + f.Replace("\n", " "));
        }

        var outPath = Path.Combine(RepoRoot(), "scorecard-explorations", "m2b-pilot-metrics.md");
        Directory.CreateDirectory(Path.GetDirectoryName(outPath)!);
        File.WriteAllText(outPath, sb.ToString());
        Console.WriteLine("M2b metrics table written to " + outPath);
    }

