    /// <summary>
    /// Gate question: does the engine re-accept a completed quest when
    /// REPEATABLE='f' (cat-34 daily board)?
    /// Answer (code + runtime): NO. AddQuest refuses completed
    /// non-repeatable quests (CharacterQuests.cs:107-120, QuestDailyLimit).
    /// The daily-reset path (ResetDailyQuests) only clears QuestDetail
    /// Daily/DailyGroup/DailyHunt/DailyLivelihood (7/9/10/11) — cat-34 quests
    /// carry detail_id=6 (Task), so they are NEVER cleared: re-accept is
    /// impossible even across days. => quest-cycle limited to the 88
    /// REPEATABLE='t' quests; cat-34 falls back to character-cycle.
    /// </summary>
    [Test]
    public async Task ReacceptGate_NonRepeatableDaily_Cat34_RefusedEvenAfterDailyReset()
    {
        PlayerbotPilotRig.SeedPilotSingletons();
        var (bot, session) = NewBot("gate-bot");

        // Quest 1959's Start component carries a REAL unit requirement:
        // CompleteQuestContext(1958) — the cat-34 board's predecessor. A real
        // character that sees this quest has 1958 in their completed flags;
        // rig it through the engine's own flag API (the same method the
        // completion path calls, CharacterQuests.SetCompletedQuestFlag).
        bot.Character.Quests.SetCompletedQuestFlag(1958, true);

        var manifest = LoadManifest("t4", 1959); // cat-34 daily (REPEATABLE='f', detail_id=6)
        var result = PlayerbotQuestDriver.DriveQuest(bot, session, manifest, 1);
        await Assert.That(result.Passed, result.ReproTrace()).IsTrue();
        await Assert.That(bot.HasCompleted(1959), "quest 1959 must be completed by the drive").IsTrue();

        // Same-day re-accept: refused by the engine gate.
        var reAccept = bot.AcceptQuest(1959, QuestAcceptorType.Item, 8017);
        await Assert.That(reAccept, "engine MUST refuse re-accept of completed REPEATABLE='f' quest (QuestDailyLimit)").IsFalse();

        // Daily-reset path: cat-34 detail_id=6 is Task, NOT in the daily family
        // (Daily=7/DailyGroup=9/DailyHunt=10/DailyLivelihood=11) -> reset does not
        // clear it -> still refused.
        bot.Character.LeaveTime = DateTime.UtcNow.AddDays(-2);
        bot.Character.Quests.CheckDailyResetAtLogin();
        await Assert.That(bot.HasCompleted(1959),
            "cat-34 (detail Task=6) completed flag must SURVIVE the daily reset — detail not in daily family").IsTrue();
        var reAcceptAfterReset = bot.AcceptQuest(1959, QuestAcceptorType.Item, 8017);
        await Assert.That(reAcceptAfterReset,
            "cat-34 quest-cycle is impossible: re-accept must still be refused after the daily reset").IsFalse();
    }

    /// <summary>
    /// Quest-cycle mode (REPEATABLE='t'): same character re-accepts a completed
    /// quest — 10 cycles on quest 5059 (Solzreed's only REPEATABLE='t' quest).
    /// </summary>
    [Test]
    public async Task QuestCycle_RepeatableQuest_SameCharacterTenCycles()
    {
        PlayerbotPilotRig.SeedPilotSingletons();
        var (bot, session) = NewBot("cycle-bot");
        var manifest = LoadManifest("t1", 5059);

        // 5059 is the jury-point daily: its Start component carries REAL unit
        // requirements — CompleteQuestContext(4784) + MotherFaction(148) +
        // CrimeRecord(1..9) + JuryPoint(>=1). A real level-45 jury-eligible
        // Nuian has all of these; rig through the engine's own surfaces (the
        // completed-flag API the completion path uses + ordinary character
        // fields). The MotherFaction gate dereferences Faction.MotherId —
        // HeadlessSession now seeds the Nuian faction (148) by default.
        bot.Character.Quests.SetCompletedQuestFlag(4784, true);
        bot.Character.JuryPoint = 1;

        var passed = 0;
        var failures = new List<string>();
        for (var cycle = 1; cycle <= 10; cycle++)
        {
            // Level gate re-evaluation per cycle (fresh accept).
            var result = PlayerbotQuestDriver.DriveQuest(bot, session, manifest, (byte)manifest.Template.Level);
            if (!result.Passed)
            {
                failures.Add($"cycle {cycle}: " + result.ReproTrace());
                break;
            }

            // State-cleanup: quest dropped from ActiveQuests, completed flag set once.
            await Assert.That(bot.IsActive(5059), $"cycle {cycle}: quest still active after completion").IsFalse();
            await Assert.That(bot.HasCompleted(5059), $"cycle {cycle}: completed flag missing").IsTrue();
            passed++;
        }

        await Assert.That(failures, "quest-cycle failures: " + string.Join("\n", failures)).IsEmpty();
        await Assert.That(passed, "quest-cycle pass rate must be 10/10").IsEqualTo(10);
        await Assert.That(bot.HasCompleted(5059), "final completed flag").IsTrue();
    }

