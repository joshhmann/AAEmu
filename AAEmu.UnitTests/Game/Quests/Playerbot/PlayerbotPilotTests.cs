    /// <summary>
    /// Character-cycle mode: 3 bots x 10 cycles through the Solzreed golden
    /// route, fresh headless character per cycle, real gates enforced
    /// (level + kind-31 chains + race). Emits the M2b metrics table.
    /// </summary>
    [Test]
    public async Task CharacterCycle_GoldenRoute_ThreeBots_TenCycles()
    {
        PlayerbotPilotRig.SeedPilotSingletons();
        var run = new PilotRun();
        var manifests = GoldenRoute.ToDictionary(q => q, q => LoadManifest("t1", q));

        for (var botId = 1; botId <= 3; botId++)
        {
            for (var cycle = 1; cycle <= 10; cycle++)
            {
                var (bot, session) = NewBot($"bot{botId}-c{cycle}");

                var leaks = new List<string>();
                var passedQuests = 0;
                var cyclePassed = true;

                foreach (var questId in GoldenRoute)
                {
                    var manifest = manifests[questId];
                    var level = (byte)Math.Max(bot.Character.Level, manifest.Template.Level);
                    var result = PlayerbotQuestDriver.DriveQuest(bot, session, manifest, level);
                    if (!result.Passed)
                    {
                        run.Failures.Add($"bot {botId} cycle {cycle}: " + result.ReproTrace());
                        cyclePassed = false;
                        break;
                    }
                    passedQuests++;
                }

                // State-cleanup checks (M2b table): 0 leaks.
                if (bot.Character.Quests.ActiveQuests.Count != 0)
                    leaks.Add($"ActiveQuests not empty ({bot.Character.Quests.ActiveQuests.Count} quests)");

                // Completed flags: every route quest completed exactly once.
                foreach (var questId in GoldenRoute)
                {
                    if (!bot.HasCompleted(questId))
                        leaks.Add($"completed flag missing for quest {questId}");
                }

                // Reward totals: the manifest's last stage expects exact inventory counts.
                foreach (var questId in GoldenRoute)
                {
                    var manifest = manifests[questId];
                    var lastStage = manifest.Stages.LastOrDefault(s => s.Expect?.RewardItems is { Count: > 0 });
                    if (lastStage?.Expect?.RewardItems != null)
                    {
                        foreach (var rewardItem in lastStage.Expect.RewardItems)
                        {
                            var found = bot.InventoryCount(rewardItem.ItemId);
                            if (found < rewardItem.Count)
                                leaks.Add($"reward total mismatch for quest {questId}: item {rewardItem.ItemId} expected >= {rewardItem.Count}, found {found}");
                        }
                    }
                }

                run.Cycles.Add(new CycleMetrics(botId, cycle, passedQuests, GoldenRoute.Length,
                    cyclePassed && leaks.Count == 0, leaks));
            }
        }

        EmitMetricsTable(run, "Solzreed golden route (character-cycle)");

        // Drift detection: no silent failures.
        await Assert.That(run.Failures,
            "DRIFT DETECTED — regression cards required:\n" + string.Join("\n", run.Failures)).IsEmpty();

        // Cycle pass rate green bar: 100% (10/10) per bot.
        foreach (var botGroup in run.Cycles.GroupBy(c => c.Bot))
        {
            var passed = botGroup.Count(c => c.Passed);
            await Assert.That(passed, $"bot {botGroup.Key} pass rate must be 10/10").IsEqualTo(10);
        }

        // Mean cycles-to-complete stable within ±1 over the last 5 cycles.
        var last5 = run.Cycles.OrderByDescending(c => (c.Bot, c.Cycle)).Take(15);
        var mean = last5.Average(c => c.Passed ? 1 : 0);
        await Assert.That(mean,
            "deterministic drive must complete in 1 cycle (mean cycles-to-complete = 1.0)").IsEqualTo(1.0);

        // State-cleanup green bar: 0 leaks over the run.
        await Assert.That(run.Cycles.Sum(c => c.CleanupLeaks.Count),
            "state-cleanup leaks: " + string.Join("; ", run.Cycles.SelectMany(c => c.CleanupLeaks).Distinct())).IsEqualTo(0);
    }

